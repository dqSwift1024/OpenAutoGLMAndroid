    fun packageName(appName: String): String = packages[appName] ?: appName

    /** 已知包名返回官方使用的应用名；桌面返回 System Home；未知包名保持原样。 */
    fun displayName(packageName: String?): String {
        if (packageName.isNullOrBlank()) return "System Home"
        if ("launcher" in packageName.lowercase()) return "System Home"
        return packages.entries.firstOrNull { it.value == packageName }?.key ?: packageName
    }
